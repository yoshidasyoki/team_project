    <script>
        function toggleTag(el) {
            el.classList.toggle('selected');

            // 選択スタイル（見た目）の切替
            if (el.classList.contains('selected')) {
                el.classList.add('ring-2', 'ring-offset-2', 'ring-blue-500');
            } else {
                el.classList.remove('ring-2', 'ring-offset-2', 'ring-blue-500');
            }

            // selectedTagsContainer 内の input 状態を更新
            updateHiddenTags();
        }

        function updateHiddenTags() {
            const container = document.getElementById('selectedTagsContainer');
            container.innerHTML = '';

            const selectedCards = document.querySelectorAll('.post-tag-card-item.selected');
            selectedCards.forEach(card => {
                const tagId = card.getAttribute('data-tag-id');
                if (tagId) {
                    const input = document.createElement('input');
                    input.type = 'hidden';
                    input.name = 'tags[]';
                    input.value = tagId;
                    container.appendChild(input);
                }
            });
        }
    </script>
